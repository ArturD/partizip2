export function preteriteExplanation(verb: { id: string; type: string; subtype: string; separable: boolean }): string {
 const form = preterite[verb.id];
 const rule = verb.type === 'regular' ? 'Regular verbs add -te (or -ete after stems such as arbeit-); do not add ge-.' : verb.subtype === 'mixed' ? 'This mixed verb changes its stem and adds -te.' : 'This irregular form uses a changed stem; ich and er/sie/es have the same form.';
 return `${verb.id} → ${form}. ${rule}${verb.separable ? ' In a main clause, place the separable prefix after the verb; include it in your answer.' : ''}`;
}
